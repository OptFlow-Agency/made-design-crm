// @vitest-environment node
import fs from 'fs'
import path from 'path'
import config from '@/payload.config'
import { getPayload } from 'payload'
import { it } from 'vitest'

/**
 * Uploads the original Maison Sabra images (public/media.old) to the configured storage (Supabase via S3 env vars)
 * and re-attaches them to the tenant's existing media docs (matched by filename) so product links stay intact.
 * Files with no matching media doc get a new one. Idempotent. Run: `pnpm seed:maison-sabra-media`.
 */
it('seeds Maison Sabra images into storage', async () => {
  if (!process.env.S3_BUCKET) throw new Error('Set S3_BUCKET (and the other S3_* vars) so uploads go to Supabase')
  const payload = await getPayload({ config: await config })
  const tenant = (await payload.find({ collection: 'tenants', where: { slug: { equals: 'maisonsabra' } }, limit: 1, depth: 0 })).docs[0]
  if (!tenant) throw new Error('Maison Sabra tenant not found')

  const dir = path.resolve(__dirname, '../../public/media.old')
  // Resized variants (-480xN, -800xN) are regenerated by Payload from the full-size file. Names ending in -1000xN are real originals.
  const originals = fs.readdirSync(dir).filter((f) => !/-(480|800)x\d+\.\w+$/.test(f))
  const existing = (await payload.find({ collection: 'media', where: { tenant: { equals: tenant.id } }, limit: 1000, depth: 0, pagination: false })).docs
  // Payload renames a colliding upload to name-1.ext, so key docs by the name without that suffix too.
  const byName = new Map<string, (typeof existing)[number]>()
  for (const m of existing) if (m.filename) byName.set(m.filename.replace(/-\d+(\.\w+)$/, '$1'), m)
  for (const m of existing) if (m.filename) byName.set(m.filename, m)

  let created = 0, updated = 0, skipped = 0
  for (const file of originals) {
    const filePath = path.join(dir, file)
    const alt = file.replace(/\.\w+$/, '').replace(/[-_]+/g, ' ')
    const doc = byName.get(file)
    if (doc) {
      // Already in storage? Skip, otherwise Payload would store a name-1.ext copy.
      if (doc.url && (await fetch(doc.url, { method: 'HEAD' })).ok) { skipped++; continue }
      await payload.update({ collection: 'media', id: doc.id, data: { alt: doc.alt || alt } as never, filePath, overrideAccess: true })
      updated++
    } else {
      await payload.create({ collection: 'media', data: { alt, tenant: tenant.id } as never, filePath, overrideAccess: true })
      created++
    }
  }
  console.log(`media seeded: ${created} created, ${updated} re-uploaded, ${skipped} already present`)
}, 300_000)
